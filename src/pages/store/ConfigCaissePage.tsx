import { useEffect, useRef, useState } from 'react'
import { useParams } from 'react-router-dom'
import {
  Alert,
  Box,
  Button,
  Chip,
  CircularProgress,
  Dialog,
  DialogActions,
  DialogContent,
  DialogTitle,
  IconButton,
  InputAdornment,
  MenuItem,
  Paper,
  Stack,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  TextField,
  Tooltip,
  Typography,
} from '@mui/material'
import {
  AddRounded,
  DeleteRounded,
  EditRounded,
  SavingsRounded,
} from '@mui/icons-material'
import { useTranslation } from 'react-i18next'
import {
  createCashTransaction,
  deleteCashTransaction,
  listCashTransactions,
  updateCashTransaction,
} from '../../api/transactions'
import { listStores } from '../../api/stores'
import { useFormatters } from '../../i18n/useFormatters'
import ConfirmDialog from '../../components/ConfirmDialog'

type CashTransactionSource = 'ORDER' | 'ADD_MONEY' | 'WITHDRAW_MONEY' | 'OTHER'

type CashTxCreateSource = 'WITHDRAW_MONEY' | 'OTHER'

interface CashTransaction {
  id: number
  title: string
  date: string
  amount: string
  source: CashTransactionSource
  order: number | null
}

const SOURCE_LABEL_KEYS: Record<CashTransactionSource, string> = {
  ORDER: 'sourceOrder',
  ADD_MONEY: 'sourceAddMoney',
  WITHDRAW_MONEY: 'sourceWithdrawMoney',
  OTHER: 'sourceOther',
}

// ORDER rows are generated by the system from a Shopify order and have no
// delete affordance; every other source can be removed by the user.
const DELETABLE_SOURCES: CashTransactionSource[] = [
  'ADD_MONEY',
  'WITHDRAW_MONEY',
  'OTHER',
]

const DELETE_WARNING_KEYS: Partial<Record<CashTransactionSource, string>> = {
  ADD_MONEY: 'deleteWarningBank',
  WITHDRAW_MONEY: 'deleteWarningBank',
}

const CREATE_SOURCE_OPTIONS: { value: CashTxCreateSource; labelKey: string }[] =
  [
    { value: 'WITHDRAW_MONEY', labelKey: 'sourceWithdrawMoney' },
    { value: 'OTHER', labelKey: 'sourceOther' },
  ]

interface TxFormDialogProps {
  open: boolean
  mode: 'create' | 'edit'
  storePk: string
  transaction: CashTransaction | null
  onClose: () => void
  onSaved: (message: string) => void
}

const emptyForm = { title: '', date: '', amount: '' }

const TxFormDialog = ({
  open,
  mode,
  storePk,
  transaction,
  onClose,
  onSaved,
}: TxFormDialogProps) => {
  const { t } = useTranslation()
  const [createSource, setCreateSource] =
    useState<CashTxCreateSource>('WITHDRAW_MONEY')
  const [form, setForm] = useState(() =>
    mode === 'edit' && transaction
      ? {
          title: transaction.title,
          date: transaction.date,
          amount: transaction.amount,
        }
      : emptyForm,
  )
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState('')

  const setField = (key: keyof typeof emptyForm, value: string) =>
    setForm((prev) => ({ ...prev, [key]: value }))

  const canSubmit =
    form.title.trim() !== '' &&
    form.date.trim() !== '' &&
    form.amount.trim() !== ''

  const handleSubmit = async () => {
    setSaving(true)
    setError('')
    try {
      if (mode === 'create') {
        await createCashTransaction(storePk, { source: createSource, ...form })
        onSaved(t('configCash.createSuccess'))
      } else if (transaction) {
        await updateCashTransaction(storePk, transaction.id, form)
        onSaved(t('configCash.updateSuccess'))
      }
    } catch {
      setError(t('common.saveFailed'))
    } finally {
      setSaving(false)
    }
  }

  return (
    <Dialog open={open} onClose={onClose} fullWidth maxWidth="xs">
      <DialogTitle>
        {mode === 'create'
          ? t('configCash.dialogTitleCreate')
          : t('configCash.dialogTitleEdit')}
      </DialogTitle>
      <DialogContent>
        <Stack spacing={2} sx={{ mt: 1 }}>
          {error && <Alert severity="error">{error}</Alert>}
          {mode === 'create' ? (
            <TextField
              select
              label={t('configCash.colSource')}
              value={createSource}
              onChange={(e) =>
                setCreateSource(e.target.value as CashTxCreateSource)
              }
              fullWidth
            >
              {CREATE_SOURCE_OPTIONS.map((opt) => (
                <MenuItem key={opt.value} value={opt.value}>
                  {t(`configCash.${opt.labelKey}`)}
                </MenuItem>
              ))}
            </TextField>
          ) : (
            <TextField
              label={t('configCash.colSource')}
              value={t(`configCash.${SOURCE_LABEL_KEYS[transaction!.source]}`, {
                defaultValue: transaction!.source,
              })}
              disabled
              fullWidth
            />
          )}
          <TextField
            label={t('configCash.colTitle')}
            value={form.title}
            onChange={(e) => setField('title', e.target.value)}
            required
            fullWidth
          />
          <TextField
            label={t('configCash.colDate')}
            type="date"
            value={form.date}
            onChange={(e) => setField('date', e.target.value)}
            required
            fullWidth
            slotProps={{ inputLabel: { shrink: true } }}
          />
          <TextField
            label={t('configCash.colAmount')}
            type="number"
            value={form.amount}
            onChange={(e) => setField('amount', e.target.value)}
            required
            fullWidth
            slotProps={{
              input: {
                endAdornment: <InputAdornment position="end">€</InputAdornment>,
                inputProps: { step: '0.01' },
              },
            }}
          />
        </Stack>
      </DialogContent>
      <DialogActions>
        <Button onClick={onClose} disabled={saving}>
          {t('common.cancel')}
        </Button>
        <Button
          variant="contained"
          onClick={handleSubmit}
          disabled={saving || !canSubmit}
          startIcon={
            saving ? <CircularProgress size={16} color="inherit" /> : undefined
          }
        >
          {mode === 'create' ? t('common.create') : t('common.save')}
        </Button>
      </DialogActions>
    </Dialog>
  )
}

const ConfigCaissePage = () => {
  const { id } = useParams()
  const { t } = useTranslation()
  const { currency, date } = useFormatters()
  const [transactions, setTransactions] = useState<CashTransaction[]>([])
  const [loading, setLoading] = useState(true)
  const [loadingMore, setLoadingMore] = useState(false)
  const [error, setError] = useState('')
  const [hasMore, setHasMore] = useState(false)
  const [cashAmount, setCashAmount] = useState<string | null>(null)
  const [reloadKey, setReloadKey] = useState(0)
  const [successMessage, setSuccessMessage] = useState('')
  const [dialogOpen, setDialogOpen] = useState(false)
  const [dialogMode, setDialogMode] = useState<'create' | 'edit'>('create')
  const [editingTx, setEditingTx] = useState<CashTransaction | null>(null)
  const [deleteDialogOpen, setDeleteDialogOpen] = useState(false)
  const [deletingTx, setDeletingTx] = useState<CashTransaction | null>(null)
  const [deleting, setDeleting] = useState(false)
  const [deleteError, setDeleteError] = useState('')
  const nextPageRef = useRef(2)
  const busyRef = useRef(false)
  const sentinelRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    listStores()
      .then((res) => {
        const store = (
          res.data.results as { id: number; cash_amount?: string }[]
        ).find((s) => s.id === Number(id))
        if (store?.cash_amount != null) setCashAmount(store.cash_amount)
      })
      .catch(() => {})
  }, [id])

  useEffect(() => {
    if (!id) return
    nextPageRef.current = 2
    busyRef.current = false
    let cancelled = false
    const load = async () => {
      setTransactions([])
      setLoading(true)
      setError('')
      setHasMore(false)
      try {
        const res = await listCashTransactions(id, 1)
        if (cancelled) return
        setTransactions(res.data.results)
        setHasMore(!!res.data.next)
      } catch {
        if (cancelled) return
        setError(t('configCash.loadError'))
      } finally {
        if (!cancelled) setLoading(false)
      }
    }
    load()
    return () => {
      cancelled = true
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id, reloadKey])

  useEffect(() => {
    if (!hasMore || !sentinelRef.current) return
    const sentinel = sentinelRef.current
    const observer = new IntersectionObserver(
      async (entries) => {
        if (!entries[0].isIntersecting || busyRef.current) return
        busyRef.current = true
        setLoadingMore(true)
        try {
          const page = nextPageRef.current
          const res = await listCashTransactions(id!, page)
          setTransactions((prev) => [...prev, ...res.data.results])
          setHasMore(!!res.data.next)
          nextPageRef.current = page + 1
        } catch {
          setError(t('configCash.loadMoreError'))
        } finally {
          busyRef.current = false
          setLoadingMore(false)
        }
      },
      { threshold: 0.1 },
    )
    observer.observe(sentinel)
    return () => observer.disconnect()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [hasMore, id])

  const openCreate = () => {
    setDialogMode('create')
    setEditingTx(null)
    setDialogOpen(true)
  }

  const openEdit = (tx: CashTransaction) => {
    setDialogMode('edit')
    setEditingTx(tx)
    setDialogOpen(true)
  }

  const handleSaved = (message: string) => {
    setDialogOpen(false)
    setSuccessMessage(message)
    setReloadKey((k) => k + 1)
  }

  const openDelete = (tx: CashTransaction) => {
    setDeletingTx(tx)
    setDeleteError('')
    setDeleteDialogOpen(true)
  }

  const closeDelete = () => {
    if (deleting) return
    setDeleteDialogOpen(false)
  }

  const handleDeleteConfirm = async () => {
    if (!deletingTx) return
    setDeleting(true)
    setDeleteError('')
    try {
      await deleteCashTransaction(id!, deletingTx.id)
      setDeleteDialogOpen(false)
      setSuccessMessage(t('configCash.deleteSuccess'))
      setReloadKey((k) => k + 1)
    } catch {
      setDeleteError(t('configCash.deleteError'))
    } finally {
      setDeleting(false)
    }
  }

  return (
    <Box>
      <Box
        sx={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          mb: 3,
        }}
      >
        <Typography variant="h5" fontWeight={700}>
          {t('configCash.title')}
        </Typography>
        <Box sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
          {cashAmount != null && (
            <Chip
              icon={<SavingsRounded />}
              label={t('configCash.cashBalance', {
                amount: currency(cashAmount),
              })}
              color="primary"
              variant="outlined"
            />
          )}
          <Button
            variant="contained"
            startIcon={<AddRounded />}
            onClick={openCreate}
          >
            {t('configCash.addButton')}
          </Button>
        </Box>
      </Box>

      {successMessage && (
        <Alert
          severity="success"
          sx={{ mb: 2 }}
          onClose={() => setSuccessMessage('')}
        >
          {successMessage}
        </Alert>
      )}

      {error && (
        <Alert severity="error" sx={{ mb: 2 }} onClose={() => setError('')}>
          {error}
        </Alert>
      )}

      {loading ? (
        <Box sx={{ display: 'flex', justifyContent: 'center', mt: 6 }}>
          <CircularProgress />
        </Box>
      ) : (
        <>
          <TableContainer component={Paper} variant="outlined">
            <Table size="small">
              <TableHead>
                <TableRow>
                  <TableCell sx={{ fontWeight: 600 }}>
                    {t('configCash.colDate')}
                  </TableCell>
                  <TableCell sx={{ fontWeight: 600 }}>
                    {t('configCash.colTitle')}
                  </TableCell>
                  <TableCell sx={{ fontWeight: 600 }}>
                    {t('configCash.colSource')}
                  </TableCell>
                  <TableCell sx={{ fontWeight: 600 }} align="right">
                    {t('configCash.colAmount')}
                  </TableCell>
                  <TableCell sx={{ fontWeight: 600 }}>
                    {t('configCash.colOrder')}
                  </TableCell>
                  <TableCell />
                </TableRow>
              </TableHead>
              <TableBody>
                {transactions.length === 0 ? (
                  <TableRow>
                    <TableCell
                      colSpan={6}
                      align="center"
                      sx={{ py: 4, color: 'text.secondary' }}
                    >
                      {t('configCash.empty')}
                    </TableCell>
                  </TableRow>
                ) : (
                  transactions.map((tx) => (
                    <TableRow key={tx.id} hover>
                      <TableCell>{date(tx.date)}</TableCell>
                      <TableCell>{tx.title}</TableCell>
                      <TableCell>
                        {t(`configCash.${SOURCE_LABEL_KEYS[tx.source]}`, {
                          defaultValue: tx.source,
                        })}
                      </TableCell>
                      <TableCell
                        align="right"
                        sx={{
                          color:
                            parseFloat(tx.amount) >= 0
                              ? 'success.main'
                              : 'error.main',
                          fontWeight: 500,
                        }}
                      >
                        {currency(tx.amount, { signDisplay: 'exceptZero' })}
                      </TableCell>
                      <TableCell>
                        {tx.order != null ? `#${tx.order}` : '—'}
                      </TableCell>
                      <TableCell sx={{ whiteSpace: 'nowrap' }}>
                        <Tooltip title={t('common.edit')}>
                          <IconButton
                            size="small"
                            onClick={() => openEdit(tx)}
                            aria-label={t('configCash.dialogTitleEdit')}
                          >
                            <EditRounded fontSize="small" />
                          </IconButton>
                        </Tooltip>
                        {DELETABLE_SOURCES.includes(tx.source) && (
                          <Tooltip title={t('common.delete')}>
                            <IconButton
                              size="small"
                              color="error"
                              onClick={() => openDelete(tx)}
                              aria-label={t('configCash.deleteAriaLabel', {
                                id: tx.id,
                              })}
                            >
                              <DeleteRounded fontSize="small" />
                            </IconButton>
                          </Tooltip>
                        )}
                      </TableCell>
                    </TableRow>
                  ))
                )}
              </TableBody>
            </Table>
          </TableContainer>

          {transactions.length > 0 && (
            <Typography
              variant="caption"
              color="text.secondary"
              sx={{ mt: 1, display: 'block' }}
            >
              {hasMore
                ? t('configCash.countMore', { count: transactions.length })
                : t('configCash.count', { count: transactions.length })}
            </Typography>
          )}
        </>
      )}

      {loadingMore && (
        <Box sx={{ display: 'flex', justifyContent: 'center', mt: 2 }}>
          <CircularProgress size={24} />
        </Box>
      )}

      <div ref={sentinelRef} style={{ height: 1 }} />

      {dialogOpen && (
        <TxFormDialog
          key={`${dialogMode}-${editingTx?.id ?? 'new'}`}
          open={dialogOpen}
          mode={dialogMode}
          storePk={id!}
          transaction={editingTx}
          onClose={() => setDialogOpen(false)}
          onSaved={handleSaved}
        />
      )}

      <ConfirmDialog
        open={deleteDialogOpen}
        title={t('configCash.deleteConfirmTitle')}
        message={t('configCash.deleteConfirmMessage', {
          title: deletingTx?.title ?? '',
        })}
        warning={
          deletingTx && DELETE_WARNING_KEYS[deletingTx.source]
            ? t(`configCash.${DELETE_WARNING_KEYS[deletingTx.source]}`)
            : undefined
        }
        loading={deleting}
        error={deleteError}
        onConfirm={handleDeleteConfirm}
        onCancel={closeDelete}
      />
    </Box>
  )
}

export default ConfigCaissePage
